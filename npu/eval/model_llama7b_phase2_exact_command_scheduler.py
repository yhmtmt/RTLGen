"""Reference model for exact Llama-2-7B Phase-2 context admission.

This model stops at the real control boundary.  It admits one context for each
remote shared-SRAM stream and one atomic context for each fifteen-source
reduction group.  Packet descriptors are generated by the endpoint adapters;
they are transport accounting, not serialized central scheduler commands.

Readiness comes from producers and SRAM residency.  The model never invents a
release cycle or physical slot/address assignment.  Adapter completion and
mesh backpressure are represented by the output ready input, matching the
ready/valid boundary expected of a future RTL context scheduler.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Any, Callable, Iterable, Mapping

TRANSPORT_ALIGNED = "aligned"
TRANSPORT_STATS_ONCE = "stats_once"
TRANSPORT_MODES = frozenset({TRANSPORT_ALIGNED, TRANSPORT_STATS_ONCE})

CLUSTER_COUNT = 16
ROOT_CLUSTER = 15
SHARED_WAVE_COUNT = 8
LOCAL_SHARED_WAVE = 4
REDUCTION_GROUP_COUNT = 4
SHARED_PACKETS_PER_CONTEXT = 68
SHARED_FLITS_PER_PACKET = 8
REDUCTION_ADAPTER_SLOT_COUNT = 2


class SchedulerError(ValueError):
    """Raised when readiness or scheduler state violates the contract."""


@dataclass(frozen=True)
class ReadinessEvent:
    """Producer/SRAM event that contributes to one context's eligibility."""

    kind: str
    cycle: int
    wave: int | None = None
    cluster: int | None = None
    source: int | None = None
    group: int | None = None
    source_base_addr: int | None = None
    destination_base_addr: int | None = None
    packet_count: int | None = None

    @classmethod
    def shared(
        cls,
        *,
        wave: int,
        cluster: int,
        cycle: int,
        source_base_addr: int | None = None,
        destination_base_addr: int | None = None,
        packet_count: int = SHARED_PACKETS_PER_CONTEXT,
    ) -> "ReadinessEvent":
        return cls(
            kind="shared",
            cycle=cycle,
            wave=wave,
            cluster=cluster,
            source_base_addr=source_base_addr,
            destination_base_addr=destination_base_addr,
            packet_count=packet_count,
        )

    @classmethod
    def reduction(cls, *, source: int, group: int, cycle: int) -> "ReadinessEvent":
        return cls(kind="reduction", cycle=cycle, source=source, group=group)

    @property
    def event_key(self) -> tuple[str, int, int]:
        if self.kind == "shared" and self.wave is not None and self.cluster is not None:
            return (self.kind, self.wave, self.cluster)
        if self.kind == "reduction" and self.group is not None and self.source is not None:
            return (self.kind, self.group, self.source)
        raise SchedulerError(f"incomplete readiness event: {self!r}")


ReleaseEvent = ReadinessEvent


@dataclass(frozen=True)
class Phase2ContextCommand:
    """One context admission and its exact downstream transport quantities."""

    kind: str
    context_id: str
    sources: tuple[int, ...]
    destination: int
    vc: int
    packet_count: int
    flit_count: int
    packet_flit_counts_per_source: tuple[int, ...]
    release_cycle: int
    source_release_cycles: tuple[int, ...]
    transport_mode: str
    storage_binding: str
    storage_slot_count: int | None
    storage_slot_policy: str
    completion_binding: str
    source_base_addr: int | None = None
    destination_base_addr: int | None = None
    wave: int | None = None
    group: int | None = None
    issue_cycle: int | None = None

    @property
    def stream_id(self) -> str:
        """Compatibility name for diagnostics written before context batching."""

        return self.context_id

    @property
    def metadata(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "context_id": self.context_id,
            "sources": list(self.sources),
            "destination": self.destination,
            "vc": self.vc,
            "packet_count": self.packet_count,
            "flit_count": self.flit_count,
            "packet_flit_counts_per_source": list(self.packet_flit_counts_per_source),
            "release_cycle": self.release_cycle,
            "source_release_cycles": list(self.source_release_cycles),
            "transport_mode": self.transport_mode,
            "storage_binding": self.storage_binding,
            "storage_slot_count": self.storage_slot_count,
            "storage_slot_policy": self.storage_slot_policy,
            "completion_binding": self.completion_binding,
            "source_base_addr": self.source_base_addr,
            "destination_base_addr": self.destination_base_addr,
            "wave": self.wave,
            "group": self.group,
            "issue_cycle": self.issue_cycle,
            "issue_cycle_semantics": "scheduler_cycle_under_supplied_destination_ready_trace",
            "latency_evidence": "none_without_measured_destination_ready_trace",
        }


# Compatibility alias.  A command now means a context command, never one
# centrally serialized packet descriptor.
Phase2Command = Phase2ContextCommand


@dataclass(frozen=True)
class SchedulerStep:
    cycle: int
    valid: bool
    ready: bool
    fired: bool
    command: Phase2ContextCommand | None


@dataclass
class _ContextState:
    key: tuple[str, int, int]
    command: Phase2ContextCommand
    admitted: bool = False


def _mode(mode: str) -> str:
    if mode not in TRANSPORT_MODES:
        raise SchedulerError(
            f"invalid transport mode {mode!r}; expected one of {sorted(TRANSPORT_MODES)!r}"
        )
    return mode


def reduction_packet_flit_counts(mode: str) -> tuple[int, ...]:
    mode = _mode(mode)
    if mode == TRANSPORT_ALIGNED:
        return (8,) * 32
    return (8,) * 20 + (7,)


def expected_counts(mode: str) -> dict[str, int]:
    """Exact context, packet-descriptor, and flit counts for one layer."""

    packet_flits = reduction_packet_flit_counts(mode)
    shared_contexts = (SHARED_WAVE_COUNT - 1) * CLUSTER_COUNT
    shared_packets = shared_contexts * SHARED_PACKETS_PER_CONTEXT
    shared_flits = shared_packets * SHARED_FLITS_PER_PACKET
    reduction_contexts = REDUCTION_GROUP_COUNT
    reduction_packets = reduction_contexts * ROOT_CLUSTER * len(packet_flits)
    reduction_flits = reduction_contexts * ROOT_CLUSTER * sum(packet_flits)
    return {
        "shared_contexts": shared_contexts,
        "reduction_contexts": reduction_contexts,
        "total_context_commands": shared_contexts + reduction_contexts,
        "shared_packets": shared_packets,
        "shared_flits": shared_flits,
        "reduction_packets": reduction_packets,
        "reduction_flits": reduction_flits,
        "total_packet_descriptors": shared_packets + reduction_packets,
        "total_packets": shared_packets + reduction_packets,
        "total_flits": shared_flits + reduction_flits,
    }


def _coerce_event(value: ReadinessEvent | Mapping[str, Any]) -> ReadinessEvent:
    if isinstance(value, ReadinessEvent):
        return value
    if not isinstance(value, Mapping):
        raise SchedulerError(f"unsupported readiness event: {value!r}")
    cycle = value.get("cycle", value.get("release_cycle"))
    if cycle is None:
        raise SchedulerError("readiness event lacks cycle/release_cycle")
    try:
        kind = str(value["kind"])
        packet_count = value.get("packet_count")
        if packet_count is None and kind == "shared":
            packet_count = SHARED_PACKETS_PER_CONTEXT
        return ReadinessEvent(
            kind=kind,
            cycle=int(cycle),
            wave=None if value.get("wave") is None else int(value["wave"]),
            cluster=None if value.get("cluster") is None else int(value["cluster"]),
            source=None if value.get("source") is None else int(value["source"]),
            group=None if value.get("group") is None else int(value["group"]),
            source_base_addr=(
                None
                if value.get("source_base_addr") is None
                else int(value["source_base_addr"])
            ),
            destination_base_addr=(
                None
                if value.get("destination_base_addr") is None
                else int(value["destination_base_addr"])
            ),
            packet_count=None if packet_count is None else int(packet_count),
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise SchedulerError(f"invalid readiness event {value!r}") from exc


def validate_readiness_events(
    events: Iterable[ReadinessEvent | Mapping[str, Any]],
) -> tuple[ReadinessEvent, ...]:
    normalized: list[ReadinessEvent] = []
    seen: dict[tuple[str, int, int], int] = {}
    for raw in events:
        event = _coerce_event(raw)
        if isinstance(event.cycle, bool) or event.cycle < 0:
            raise SchedulerError(f"readiness cycle must be a non-negative integer: {event!r}")
        if event.kind == "shared":
            valid = (
                event.wave is not None
                and event.cluster is not None
                and 0 <= event.wave < SHARED_WAVE_COUNT
                and 0 <= event.cluster < CLUSTER_COUNT
                and event.packet_count is not None
                and event.packet_count > 0
            )
        elif event.kind == "reduction":
            valid = (
                event.source is not None
                and event.group is not None
                and 0 <= event.source < ROOT_CLUSTER
                and 0 <= event.group < REDUCTION_GROUP_COUNT
            )
        else:
            raise SchedulerError(f"invalid readiness event kind: {event.kind!r}")
        if not valid:
            raise SchedulerError(f"invalid {event.kind} readiness event: {event!r}")
        if event.kind == "shared":
            for name, address in (
                ("source_base_addr", event.source_base_addr),
                ("destination_base_addr", event.destination_base_addr),
            ):
                if address is not None and (address < 0 or (address & 0xFF) != 0):
                    raise SchedulerError(
                        f"shared readiness {name} must be a non-negative 256-byte-aligned address"
                    )
        key = event.event_key
        if key in seen:
            if event.cycle < seen[key]:
                raise SchedulerError(
                    f"readiness event cycle regressed for stream {key!r}: "
                    f"{seen[key]} to {event.cycle}"
                )
            raise SchedulerError(f"duplicate readiness event for stream {key!r}")
        seen[key] = event.cycle
        normalized.append(event)
    return tuple(normalized)


def all_readiness_events(
    *,
    shared_release_cycle: int | Callable[[int, int], int] = 0,
    reduction_release_cycle: int | Callable[[int, int], int] = 100,
    shared_source_base_addr: int | Callable[[int, int], int] | None = None,
    shared_destination_base_addr: int | Callable[[int, int], int] | None = None,
    shared_packet_count: int | Callable[[int, int], int] = SHARED_PACKETS_PER_CONTEXT,
) -> tuple[ReadinessEvent, ...]:
    def cycle_of(value: int | Callable[[int, int], int], first: int, second: int) -> int:
        return value(first, second) if callable(value) else value

    def optional_value_of(
        value: int | Callable[[int, int], int] | None,
        first: int,
        second: int,
    ) -> int | None:
        return value(first, second) if callable(value) else value

    events = [
        ReadinessEvent.shared(
            wave=wave,
            cluster=cluster,
            cycle=cycle_of(shared_release_cycle, wave, cluster),
            source_base_addr=optional_value_of(
                shared_source_base_addr, wave, cluster
            ),
            destination_base_addr=optional_value_of(
                shared_destination_base_addr, wave, cluster
            ),
            packet_count=cycle_of(shared_packet_count, wave, cluster),
        )
        for wave in range(SHARED_WAVE_COUNT)
        if wave != LOCAL_SHARED_WAVE
        for cluster in range(CLUSTER_COUNT)
    ]
    events.extend(
        ReadinessEvent.reduction(
            source=source,
            group=group,
            cycle=cycle_of(reduction_release_cycle, group, source),
        )
        for group in range(REDUCTION_GROUP_COUNT)
        for source in range(ROOT_CLUSTER)
    )
    return tuple(sorted(events, key=lambda event: (event.cycle, event.event_key)))


def _shared_source(wave: int, cluster: int) -> int:
    shifts = (4, 7, 10, 13, 0, 3, 6, 9)
    return (cluster + shifts[wave]) % CLUSTER_COUNT


class ExactPhase2CommandScheduler:
    """Deterministic ready/valid model for context admission only."""

    timing_evidence = "none_without_measured_destination_ready_trace"

    def __init__(
        self,
        events: Iterable[ReadinessEvent | Mapping[str, Any]],
        *,
        transport_mode: str = TRANSPORT_ALIGNED,
    ) -> None:
        self.transport_mode = _mode(transport_mode)
        self.events = validate_readiness_events(events)
        self._event_by_key = {event.event_key: event for event in self.events}
        self._states: list[_ContextState] = []
        self._build_contexts()
        self.cycle = 0
        self._rr_cursor = 0
        self._selected_index: int | None = None
        self._accepted: list[Phase2ContextCommand] = []

    def _build_contexts(self) -> None:
        for wave in range(SHARED_WAVE_COUNT):
            if wave == LOCAL_SHARED_WAVE:
                continue
            for cluster in range(CLUSTER_COUNT):
                key = ("shared", wave, cluster)
                event = self._event_by_key.get(key)
                if event is None:
                    continue
                self._states.append(
                    _ContextState(
                        key=key,
                        command=Phase2ContextCommand(
                            kind="shared",
                            context_id=f"shared:w{wave}:c{cluster}",
                            sources=(_shared_source(wave, cluster),),
                            destination=cluster,
                            vc=0,
                            packet_count=int(event.packet_count),
                            flit_count=int(event.packet_count) * SHARED_FLITS_PER_PACKET,
                            packet_flit_counts_per_source=(SHARED_FLITS_PER_PACKET,)
                            * int(event.packet_count),
                            release_cycle=event.cycle,
                            source_release_cycles=(event.cycle,),
                            transport_mode=self.transport_mode,
                            storage_binding="external_shared_sram_residency_completion",
                            storage_slot_count=None,
                            storage_slot_policy="external_sram_residency_and_completion",
                            completion_binding="external_sram_stream_adapter_completion",
                            source_base_addr=event.source_base_addr,
                            destination_base_addr=event.destination_base_addr,
                            wave=wave,
                        ),
                    )
                )

        packet_flits = reduction_packet_flit_counts(self.transport_mode)
        for group in range(REDUCTION_GROUP_COUNT):
            source_events = [
                self._event_by_key.get(("reduction", group, source))
                for source in range(ROOT_CLUSTER)
            ]
            if not all(event is not None for event in source_events):
                continue
            cycles = tuple(event.cycle for event in source_events if event is not None)
            self._states.append(
                _ContextState(
                    key=("reduction_group", group, 0),
                    command=Phase2ContextCommand(
                        kind="reduction_group",
                        context_id=f"reduction:g{group}:all15",
                        sources=tuple(range(ROOT_CLUSTER)),
                        destination=ROOT_CLUSTER,
                        vc=1,
                        packet_count=ROOT_CLUSTER * len(packet_flits),
                        flit_count=ROOT_CLUSTER * sum(packet_flits),
                        packet_flit_counts_per_source=packet_flits,
                        release_cycle=max(cycles),
                        source_release_cycles=cycles,
                        transport_mode=self.transport_mode,
                        storage_binding="adapter_owned_dynamic_two_slot_ping_pong",
                        storage_slot_count=REDUCTION_ADAPTER_SLOT_COUNT,
                        storage_slot_policy="per_source_dynamic_two_slot_ping_pong_by_completion",
                        completion_binding="shared_root_rx_descriptor_completion_releases_tx",
                        group=group,
                    ),
                )
            )

    @property
    def accepted_commands(self) -> tuple[Phase2ContextCommand, ...]:
        return tuple(self._accepted)

    @property
    def done(self) -> bool:
        return all(state.admitted for state in self._states)

    @property
    def complete_workload(self) -> bool:
        return not self.missing_readiness_events

    @property
    def missing_readiness_events(self) -> tuple[tuple[str, int, int], ...]:
        expected = set(self.expected_event_keys())
        return tuple(sorted(expected - set(self._event_by_key)))

    @staticmethod
    def expected_event_keys() -> tuple[tuple[str, int, int], ...]:
        shared = [
            ("shared", wave, cluster)
            for wave in range(SHARED_WAVE_COUNT)
            if wave != LOCAL_SHARED_WAVE
            for cluster in range(CLUSTER_COUNT)
        ]
        reduction = [
            ("reduction", group, source)
            for group in range(REDUCTION_GROUP_COUNT)
            for source in range(ROOT_CLUSTER)
        ]
        return tuple(shared + reduction)

    # Compatibility name used by callers of the earlier stream model.
    expected_stream_keys = expected_event_keys

    def require_complete_events(self) -> None:
        if self.missing_readiness_events:
            raise SchedulerError(
                f"missing readiness events for {len(self.missing_readiness_events)} streams; "
                f"first={self.missing_readiness_events[0]!r}"
            )

    def _eligible(self, index: int) -> bool:
        state = self._states[index]
        if state.admitted or state.command.release_cycle > self.cycle:
            return False
        if state.command.kind == "reduction_group":
            return all(
                other.admitted
                for other in self._states
                if other.command.kind == "reduction_group"
                and other.command.group is not None
                and other.command.group < state.command.group
            )
        return True

    def _select(self) -> int | None:
        if self._selected_index is not None:
            return self._selected_index
        for offset in range(len(self._states)):
            index = (self._rr_cursor + offset) % len(self._states)
            if self._eligible(index):
                self._selected_index = index
                return index
        return None

    def peek(self) -> Phase2ContextCommand | None:
        index = self._select()
        return None if index is None else self._states[index].command

    def step(self, output_ready: bool = True) -> SchedulerStep:
        if not isinstance(output_ready, bool):
            raise SchedulerError("output_ready must be bool")
        index = self._select()
        command = None if index is None else self._states[index].command
        fired = command is not None and output_ready
        observed = command
        if fired and index is not None:
            observed = replace(command, issue_cycle=self.cycle)
            self._states[index].admitted = True
            self._accepted.append(observed)
            self._rr_cursor = (index + 1) % len(self._states)
            self._selected_index = None
        result = SchedulerStep(
            cycle=self.cycle,
            valid=command is not None,
            ready=output_ready,
            fired=fired,
            command=observed,
        )
        self.cycle += 1
        return result

    def run(
        self,
        output_ready: bool | Callable[[int], bool] = True,
        *,
        max_cycles: int = 10_000_000,
        require_complete: bool = False,
    ) -> tuple[Phase2ContextCommand, ...]:
        if max_cycles <= 0:
            raise SchedulerError("max_cycles must be positive")
        if require_complete:
            self.require_complete_events()
        while not self.done:
            if self.cycle >= max_cycles:
                raise SchedulerError("scheduler exceeded max_cycles")
            if self._select() is None:
                future = [
                    state.command.release_cycle
                    for state in self._states
                    if not state.admitted and state.command.release_cycle > self.cycle
                ]
                if not future:
                    raise SchedulerError("scheduler is blocked by context ordering")
            ready = output_ready(self.cycle) if callable(output_ready) else output_ready
            self.step(ready)
        return self.accepted_commands


def derive_commands(
    events: Iterable[ReadinessEvent | Mapping[str, Any]],
    *,
    transport_mode: str = TRANSPORT_ALIGNED,
    output_ready: bool | Callable[[int], bool] = True,
    max_cycles: int = 10_000_000,
    require_complete: bool = False,
) -> tuple[Phase2ContextCommand, ...]:
    return ExactPhase2CommandScheduler(events, transport_mode=transport_mode).run(
        output_ready,
        max_cycles=max_cycles,
        require_complete=require_complete,
    )


build_commands = derive_commands
