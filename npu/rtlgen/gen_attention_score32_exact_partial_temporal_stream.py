_GENERATOR = "npu/rtlgen/gen_attention_score32_exact_partial_temporal_stream.py"


def _load(path: Path) -> JsonDict:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise SystemExit(f"config must decode to a JSON object: {path}")
    return payload


def _clog2(value: int) -> int:
    resolved = 1
    while (1 << resolved) < max(2, int(value)):
        resolved += 1
    return resolved


def _validate(config: JsonDict) -> JsonDict:
    top_name = str(config.get("top_name") or "").strip()
    body = config.get(_CONFIG_KEY)
    if not top_name or not isinstance(body, dict):
        raise SystemExit(f"config requires top_name and {_CONFIG_KEY}")

    heads = int(body.get("heads", 32))
    value_slices = int(body.get("value_slices", VALUE_SLICES))
    head_id_bits = int(body.get("head_id_bits", HEAD_ID_BITS))
    fifo_depth = int(body.get("fifo_depth", 4))
    sequence_id_bits = int(body.get("sequence_id_bits", 16))
    window_index_bits = int(body.get("window_index_bits", 14))
    window_count_bits = int(body.get("window_count_bits", 15))
    max_window_count = int(body.get("max_window_count", 16384))
    exp_scale_impl = str(body.get("exp_scale_impl", FACTORED_H33_L64_MUL_EXACT)).strip()
    keep_hierarchy = bool(body.get("keep_hierarchy", True))

    if heads != 32:
        raise SystemExit("heads must remain fixed at 32")
    if value_slices != VALUE_SLICES:
        raise SystemExit("value_slices must remain fixed at 16")
    if head_id_bits != HEAD_ID_BITS:
        raise SystemExit("head_id_bits must remain fixed at 5")
    if sequence_id_bits != 16:
        raise SystemExit("sequence_id_bits must remain fixed at 16")
    if window_index_bits != 14:
        raise SystemExit("window_index_bits must remain fixed at 14")
    if window_count_bits != 15:
        raise SystemExit("window_count_bits must remain fixed at 15")
    if max_window_count != 16384:
        raise SystemExit("max_window_count must remain fixed at 16384")
    if fifo_depth < 2 or fifo_depth > 16 or fifo_depth & (fifo_depth - 1):
        raise SystemExit("fifo_depth must be a power of two in [2, 16]")

    return {
        "top_name": top_name,
        "heads": heads,
        "value_slices": value_slices,
        "head_id_bits": head_id_bits,
        "fifo_depth": fifo_depth,
        "sequence_id_bits": sequence_id_bits,
        "window_index_bits": window_index_bits,
        "window_count_bits": window_count_bits,
        "max_window_count": max_window_count,
        "exp_scale_impl": exp_scale_impl,
        "keep_hierarchy": keep_hierarchy,
    }


def _reset_memory(prefix: str, width: str, count: int, value: str) -> str:
    return "\n".join(f"      {prefix}[{index}] <= {width}'d{value};" for index in range(count))


def _reset_signed_memory(prefix: str, width: str, count: int, value: str) -> str:
    return "\n".join(f"      {prefix}[{index}] <= {width}'sd{value};" for index in range(count))


def _reset_bit_memory(prefix: str, count: int, value: str) -> str:
    return "\n".join(f"      {prefix}[{index}] <= 1'b{value};" for index in range(count))


def _lowest_pending_function() -> str:
    return """  function automatic [HEAD_ID_BITS-1:0] lowest_pending_head;
    input [HEADS-1:0] pending;
    integer scan;
    begin
      lowest_pending_head = {HEAD_ID_BITS{1'b0}};
      for (scan = HEADS - 1; scan >= 0; scan = scan - 1) begin
        if (pending[scan]) lowest_pending_head = scan[HEAD_ID_BITS-1:0];
      end
    end
  endfunction"""


