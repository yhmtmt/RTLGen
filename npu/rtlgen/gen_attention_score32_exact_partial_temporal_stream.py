def _top_pin_bits(*, fifo_depth: int) -> int:
    input_bits = 1 + 16 + HEAD_ID_BITS + 14 + 15 + 16 + 32 + 33 + _clog2(VALUE_SLICES) + 1 + PARTIAL_PAYLOAD_BITS
    output_bits = 1 + 16 + HEAD_ID_BITS + 15 + 16 + 32 + 33 + _clog2(VALUE_SLICES) + 1 + PARTIAL_PAYLOAD_BITS
    monitor_bits = (7 * 32) + (_clog2(fifo_depth) + 1) + 1
    return 2 + input_bits + output_bits + monitor_bits


def generate(config: JsonDict, out_dir: Path) -> None:
    params = _validate(json.loads(json.dumps(config)))
    top_name = str(params["top_name"])
    merge_top = f"{top_name}__pair_merge"
    out_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="score32_exact_partial_temporal_stream_") as temp_dir_name:
        merge_dir = Path(temp_dir_name) / "merge"
        generate_merge(
            {
                "top_name": merge_top,
                "attention_score32_online_state_merge": {
                    "value_slices": int(params["value_slices"]),
                    "head_id_bits": int(params["head_id_bits"]),
                    "exp_scale_impl": str(params["exp_scale_impl"]),
                    "keep_hierarchy": bool(params["keep_hierarchy"]),
                },
            },
            merge_dir,
        )
        merge_rtl = (merge_dir / "top.v").read_text(encoding="utf-8")
        merge_manifest = json.loads(
            (merge_dir / "attention_score32_online_state_merge_manifest.json").read_text(encoding="utf-8")
        )

    (out_dir / "top.v").write_text(
        merge_rtl
        + "\n\n"
        + _top(top_name=top_name, merge_top=merge_top, fifo_depth=int(params["fifo_depth"]))
        + "\n",
        encoding="utf-8",
    )
    (out_dir / "config.json").write_text(json.dumps(config, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest = {
        "version": 1,
        "top_name": top_name,
        "generator": _GENERATOR,
        "semantic_profile": "score32_exact_partial_temporal_stream_v1",
        "heads": int(params["heads"]),
        "value_slices": int(params["value_slices"]),
        "head_id_bits": int(params["head_id_bits"]),
        "sequence_id_bits": int(params["sequence_id_bits"]),
        "window_index_bits": int(params["window_index_bits"]),
        "window_count_bits": int(params["window_count_bits"]),
        "max_window_count": int(params["max_window_count"]),
        "fifo_depth": int(params["fifo_depth"]),
        "fifo_depth_contract": "power_of_two_depth_2_to_16_ready_valid_input_buffer",
        "partial_payload_bits_per_beat": PARTIAL_PAYLOAD_BITS,
        "partial_link_bits_per_input_beat": PARTIAL_LINK_BITS + 16 + 14 + 15,
        "result_interface": "ready_valid_exact_partial_temporal_head_slice_stream",
        "equivalence_hash": False,
        "exp_scale_impl": str(params["exp_scale_impl"]),
        "command_schedule_contract": (
            "strict_per_head_ordered_windows_and_slices_one_active_sequence_per_head_emit_16_beats_on_completion"
        ),
        "fail_closed_protocol_error": True,
        "remaining_abstractions": [
            "upstream_service_command_metadata_binding",
            "service_to_temporal_reducer_clock_domain_crossing",
            "downstream_full_context_final_normalizer",
            "physical_sram_macro_mapping_for_persistent_state",
            "physical_ppa",
        ],
        "top_pin_bits": _top_pin_bits(fifo_depth=int(params["fifo_depth"])),
        "submodule_manifests": {"pair_merge": merge_manifest},
    }
    if isinstance(config.get("probe_defaults"), dict):
        manifest["checked_in_probe_defaults"] = config["probe_defaults"]
    (out_dir / _MANIFEST_NAME).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    generate(_load(args.config), args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
