JsonDict = dict[str, Any]


def _validate(config: JsonDict) -> JsonDict:
    top_name = str(config.get("top_name") or "").strip()
    body = config.get(CONFIG_KEY)
    if not top_name or not isinstance(body, dict):
        raise SystemExit(f"config requires top_name and {CONFIG_KEY}")
    producers = int(body.get("producers", 53))
    if producers not in {53, 54}:
        raise SystemExit("producers must be exactly 53 or 54")
    return {"top_name": top_name, "producers": producers}


def _top(*, top_name: str, producers: int) -> str:
    lanes = producers * STREAMS
    return f"""// Auto-generated by npu/rtlgen/gen_attention_score32_exact_cluster_sram_service_gqa8.py
module {top_name} (
    input  wire clk,
    input  wire rst_n,
    input  wire fill_target_valid,
    output wire fill_target_ready,
    input  wire fill_target_buffer_sel,
    input  wire [15:0] fill_target_command_id,
    input  wire [{COMMAND_HEAD_BASE_W - 1}:0] fill_target_head_base,
    input  wire [{COMMAND_WAVE_W - 1}:0] fill_target_wave_index,
    input  wire fill_valid,
    output wire fill_ready,
    input  wire fill_buffer_sel,
    input  wire fill_stream,
    input  wire [5:0] fill_block_slot,
    input  wire [{VALUE_SLICE_W - 1}:0] fill_slice,
    input  wire [{ROW_BITS - 1}:0] fill_data,
    input  wire command_valid,
    output wire command_ready,
    input  wire command_buffer_sel,
    input  wire [15:0] command_id,
    input  wire [{COMMAND_HEAD_BASE_W - 1}:0] command_head_base,
    input  wire [{COMMAND_WAVE_W - 1}:0] command_wave_index,
    input  wire command_release_valid,
    input  wire command_release_buffer_sel,
    input  wire [{lanes - 1}:0] value_read_req_valid,
    output reg  [{lanes - 1}:0] value_read_req_ready,
    input  wire [{lanes * VALUE_REQ_ADDR_W - 1}:0] value_read_req_address,
    input  wire [{lanes * VALUE_SLICE_W - 1}:0] value_read_req_slice,
    output wire [{lanes - 1}:0] value_response_valid,
    input  wire [{lanes - 1}:0] value_response_ready,
    output wire [{lanes * VALUE_REQ_ADDR_W - 1}:0] value_response_address,
    output wire [{lanes * VALUE_SLICE_W - 1}:0] value_response_slice,
    output wire [{lanes * ROW_BITS - 1}:0] value_response_matrix,
    output wire [{lanes * TAG_W - 1}:0] value_response_tag,
    output wire [31:0] cycle_count,
    output wire [31:0] fill_target_accept_count,
    output wire [31:0] fill_row_accept_count,
    output wire [31:0] fill_stall_cycles,
    output wire [31:0] request_accept_count,
    output wire [31:0] request_stall_cycles,
    output wire [31:0] response_accept_count,
    output wire [31:0] response_stall_cycles,
    output wire [31:0] bank_conflict_count,
    output wire [31:0] command_accept_count,
    output wire [31:0] command_release_count,
    output wire [11:0] buffer0_occupancy_rows,
    output wire [11:0] buffer1_occupancy_rows,
    output wire [7:0] outstanding_response_occupancy,
    output wire protocol_error_invalid_metadata,
    output wire protocol_error_invalid_address,
    output wire protocol_error_residency,
    output wire protocol_error_overwrite,
    output wire protocol_error_command,
    output wire protocol_error
);
  localparam integer PRODUCERS = {producers};
  localparam integer STREAMS = {STREAMS};
  localparam integer LANES = {lanes};
  localparam integer BANKS = {BANKS};
  localparam integer BLOCK_SLOTS_PER_STREAM = {BLOCK_SLOTS_PER_STREAM};
  localparam integer ROW_BITS = {ROW_BITS};
  localparam integer ROWS_PER_BANK_PER_BUFFER = {ROWS_PER_BANK_PER_BUFFER};
  localparam integer REQUIRED_FILL_ROWS = {ROWS_PER_BUFFER};
  localparam integer BUFFER_BYTES = {BUFFER_BYTES};
  localparam integer DOUBLE_BUFFER_BYTES = {DOUBLE_BUFFER_BYTES};
  localparam integer VALUE_REQ_ADDR_W = {VALUE_REQ_ADDR_W};
  localparam integer VALUE_SLICE_W = {VALUE_SLICE_W};
  localparam integer TAG_W = {TAG_W};
  localparam integer RESP_FIFO_DEPTH = {RESP_FIFO_DEPTH};

  reg [ROW_BITS-1:0] bank_mem [0:BANKS-1][0:1][0:ROWS_PER_BANK_PER_BUFFER-1];
  reg row_valid_q [0:1][0:BANKS-1][0:ROWS_PER_BANK_PER_BUFFER-1];
  reg [11:0] fill_target_count_q [0:1];
  reg fill_target_active_q;
  reg fill_target_buffer_q;
  reg [15:0] fill_target_command_id_q;
  reg [4:0] fill_target_head_base_q;
  reg [2:0] fill_target_wave_index_q;
  reg [1:0] fill_target_resident_q;
  reg [15:0] resident_command_id_q [0:1];
  reg [4:0] resident_head_base_q [0:1];
  reg [2:0] resident_wave_index_q [0:1];

  reg command_active_q;
  reg command_buffer_q;
  reg [15:0] active_command_id_q;
  reg [4:0] active_head_base_q;
  reg [2:0] active_wave_index_q;

  reg [LANES-1:0] lane_resp_valid_q;
  reg [VALUE_REQ_ADDR_W-1:0] lane_resp_address_q [0:LANES-1];
  reg [VALUE_SLICE_W-1:0] lane_resp_slice_q [0:LANES-1];
  reg [ROW_BITS-1:0] lane_resp_data_q [0:LANES-1];
  reg [TAG_W-1:0] lane_resp_tag_q [0:LANES-1];
  integer bank_rr_q [0:BANKS-1];

  reg [31:0] cycle_count_q;
  reg [31:0] fill_target_accept_count_q;
  reg [31:0] fill_row_accept_count_q;
  reg [31:0] fill_stall_cycles_q;
  reg [31:0] request_accept_count_q;
  reg [31:0] request_stall_cycles_q;
  reg [31:0] response_accept_count_q;
  reg [31:0] response_stall_cycles_q;
  reg [31:0] bank_conflict_count_q;
  reg [31:0] command_accept_count_q;
  reg [31:0] command_release_count_q;
  reg protocol_error_invalid_metadata_q;
  reg protocol_error_invalid_address_q;
  reg protocol_error_residency_q;
  reg protocol_error_overwrite_q;
  reg protocol_error_command_q;

  integer lane;
  integer bank;
  integer candidate;
  integer offset;
  integer selected_lane_r [0:BANKS-1];
  integer bank_candidate_count_r [0:BANKS-1];
  integer selected_producer_r;
  integer resolved_slot_base_r;
  integer resolved_block_count_r;
  integer selected_block_slot_r;
  integer selected_row_r;
  integer outstanding_count_r;
  integer request_accept_delta_r;
  integer request_stall_delta_r;
  integer response_accept_delta_r;
  integer response_stall_delta_r;
  integer bank_conflict_delta_r;
  reg [VALUE_REQ_ADDR_W-1:0] relative_addr_r;
  reg [VALUE_SLICE_W-1:0] selected_slice_r;

  function integer resolve_block_count;
    input integer producer_index;
    input [4:0] head_base;
    integer group_index;
    integer extra_count;
    integer extra_start;
    begin
      group_index = head_base >> 3;
      extra_count = (PRODUCERS == 53) ? 11 : 10;
      extra_start = group_index * extra_count;
      resolve_block_count =
          ((producer_index >= extra_start) && (producer_index < extra_start + extra_count)) ? 2 : 1;
    end
  endfunction

  function integer resolve_slot_base;
    input integer producer_index;
    input [4:0] head_base;
    integer group_index;
    integer extra_count;
    integer extra_start;
    integer extras_before;
    begin
      group_index = head_base >> 3;
      extra_count = (PRODUCERS == 53) ? 11 : 10;
      extra_start = group_index * extra_count;
      if (producer_index <= extra_start)
        extras_before = 0;
      else if (producer_index >= extra_start + extra_count)
        extras_before = extra_count;
      else
        extras_before = producer_index - extra_start;
      resolve_slot_base = producer_index + extras_before;
    end
  endfunction

  function [TAG_W-1:0] build_resp_tag;
    input integer lane_index;
    input [VALUE_REQ_ADDR_W-1:0] relative_address;
    input [VALUE_SLICE_W-1:0] slice_index;
    begin
      build_resp_tag = {{2'b00, lane_index[6:0], relative_address[2:0], slice_index}};
    end
  endfunction

  wire fill_target_metadata_valid =
      ((fill_target_head_base == 5'd0) || (fill_target_head_base == 5'd8) ||
       (fill_target_head_base == 5'd16) || (fill_target_head_base == 5'd24));
  assign fill_target_ready = !fill_target_active_q &&
      !fill_target_resident_q[fill_target_buffer_sel] &&
      !(command_active_q && command_buffer_q == fill_target_buffer_sel) &&
      fill_target_metadata_valid;
  assign fill_ready = fill_target_active_q;

  wire command_metadata_valid =
      ((command_head_base == 5'd0) || (command_head_base == 5'd8) ||
       (command_head_base == 5'd16) || (command_head_base == 5'd24));
  wire command_resident_match = fill_target_resident_q[command_buffer_sel] &&
      resident_command_id_q[command_buffer_sel] == command_id &&
      resident_head_base_q[command_buffer_sel] == command_head_base &&
      resident_wave_index_q[command_buffer_sel] == command_wave_index;
  assign command_ready = !command_active_q && command_metadata_valid && command_resident_match;

  assign value_response_valid = lane_resp_valid_q;
  genvar gi;
  generate
    for (gi = 0; gi < LANES; gi = gi + 1) begin : g_response
      assign value_response_address[(gi * VALUE_REQ_ADDR_W) +: VALUE_REQ_ADDR_W] = lane_resp_address_q[gi];
      assign value_response_slice[(gi * VALUE_SLICE_W) +: VALUE_SLICE_W] = lane_resp_slice_q[gi];
      assign value_response_matrix[(gi * ROW_BITS) +: ROW_BITS] = lane_resp_data_q[gi];
      assign value_response_tag[(gi * TAG_W) +: TAG_W] = lane_resp_tag_q[gi];
    end
  endgenerate

  assign cycle_count = cycle_count_q;
  assign fill_target_accept_count = fill_target_accept_count_q;
  assign fill_row_accept_count = fill_row_accept_count_q;
  assign fill_stall_cycles = fill_stall_cycles_q;
  assign request_accept_count = request_accept_count_q;
  assign request_stall_cycles = request_stall_cycles_q;
  assign response_accept_count = response_accept_count_q;
  assign response_stall_cycles = response_stall_cycles_q;
  assign bank_conflict_count = bank_conflict_count_q;
  assign command_accept_count = command_accept_count_q;
  assign command_release_count = command_release_count_q;
  assign buffer0_occupancy_rows = fill_target_count_q[0];
  assign buffer1_occupancy_rows = fill_target_count_q[1];
  assign outstanding_response_occupancy = outstanding_count_r[7:0];
  assign protocol_error_invalid_metadata = protocol_error_invalid_metadata_q;
  assign protocol_error_invalid_address = protocol_error_invalid_address_q;
  assign protocol_error_residency = protocol_error_residency_q;
  assign protocol_error_overwrite = protocol_error_overwrite_q;
  assign protocol_error_command = protocol_error_command_q;
  assign protocol_error = protocol_error_invalid_metadata_q || protocol_error_invalid_address_q ||
      protocol_error_residency_q || protocol_error_overwrite_q || protocol_error_command_q;

  always @* begin
    value_read_req_ready = {{LANES{{1'b0}}}};
    outstanding_count_r = 0;
    for (lane = 0; lane < LANES; lane = lane + 1)
      if (lane_resp_valid_q[lane])
        outstanding_count_r = outstanding_count_r + 1;
    for (bank = 0; bank < BANKS; bank = bank + 1) begin
      selected_lane_r[bank] = -1;
      bank_candidate_count_r[bank] = 0;
      if (command_active_q) begin
        for (offset = 0; offset < LANES; offset = offset + 1) begin
          candidate = bank_rr_q[bank] + offset;
          if (candidate >= LANES)
            candidate = candidate - LANES;
          if (value_read_req_valid[candidate] &&
              (value_read_req_slice[(candidate * VALUE_SLICE_W) +: VALUE_SLICE_W] == bank) &&
              (!lane_resp_valid_q[candidate] || value_response_ready[candidate])) begin
            bank_candidate_count_r[bank] = bank_candidate_count_r[bank] + 1;
            if (selected_lane_r[bank] < 0)
              selected_lane_r[bank] = candidate;
          end
        end
        if (selected_lane_r[bank] >= 0)
          value_read_req_ready[selected_lane_r[bank]] = 1'b1;
      end
    end
  end

  always @(posedge clk) begin
    if (!rst_n) begin
      fill_target_active_q <= 1'b0;
      fill_target_resident_q <= 2'b00;
      command_active_q <= 1'b0;
      lane_resp_valid_q <= {{LANES{{1'b0}}}};
      cycle_count_q <= 0;
      fill_target_accept_count_q <= 0;
      fill_row_accept_count_q <= 0;
      fill_stall_cycles_q <= 0;
      request_accept_count_q <= 0;
      request_stall_cycles_q <= 0;
      response_accept_count_q <= 0;
      response_stall_cycles_q <= 0;
      bank_conflict_count_q <= 0;
      command_accept_count_q <= 0;
      command_release_count_q <= 0;
      fill_target_count_q[0] <= 0;
      fill_target_count_q[1] <= 0;
      protocol_error_invalid_metadata_q <= 1'b0;
      protocol_error_invalid_address_q <= 1'b0;
      protocol_error_residency_q <= 1'b0;
      protocol_error_overwrite_q <= 1'b0;
      protocol_error_command_q <= 1'b0;
      for (bank = 0; bank < BANKS; bank = bank + 1) begin
        bank_rr_q[bank] <= 0;
        for (lane = 0; lane < ROWS_PER_BANK_PER_BUFFER; lane = lane + 1) begin
          row_valid_q[0][bank][lane] <= 1'b0;
          row_valid_q[1][bank][lane] <= 1'b0;
        end
      end
    end else begin
      cycle_count_q <= cycle_count_q + 1'b1;

      request_accept_delta_r = 0;
      request_stall_delta_r = 0;
      response_accept_delta_r = 0;
      response_stall_delta_r = 0;
      bank_conflict_delta_r = 0;

      if (fill_target_valid && fill_target_ready) begin
        fill_target_active_q <= 1'b1;
        fill_target_buffer_q <= fill_target_buffer_sel;
        fill_target_command_id_q <= fill_target_command_id;
        fill_target_head_base_q <= fill_target_head_base;
        fill_target_wave_index_q <= fill_target_wave_index;
        fill_target_count_q[fill_target_buffer_sel] <= 0;
        fill_target_accept_count_q <= fill_target_accept_count_q + 1'b1;
        for (bank = 0; bank < BANKS; bank = bank + 1)
          for (lane = 0; lane < ROWS_PER_BANK_PER_BUFFER; lane = lane + 1)
            row_valid_q[fill_target_buffer_sel][bank][lane] <= 1'b0;
      end

      if (fill_valid && !fill_ready)
        fill_stall_cycles_q <= fill_stall_cycles_q + 1'b1;
      if (fill_valid && fill_ready) begin
        if (fill_buffer_sel != fill_target_buffer_q) begin
          protocol_error_invalid_metadata_q <= 1'b1;
        end else begin
          selected_row_r = fill_stream * BLOCK_SLOTS_PER_STREAM + fill_block_slot;
          if (row_valid_q[fill_buffer_sel][fill_slice][selected_row_r]) begin
            protocol_error_overwrite_q <= 1'b1;
          end else begin
            bank_mem[fill_slice][fill_buffer_sel][selected_row_r] <= fill_data;
            row_valid_q[fill_buffer_sel][fill_slice][selected_row_r] <= 1'b1;
            fill_row_accept_count_q <= fill_row_accept_count_q + 1'b1;
            fill_target_count_q[fill_buffer_sel] <= fill_target_count_q[fill_buffer_sel] + 1'b1;
            if (fill_target_count_q[fill_buffer_sel] + 1'b1 == REQUIRED_FILL_ROWS) begin
              fill_target_active_q <= 1'b0;
              fill_target_resident_q[fill_buffer_sel] <= 1'b1;
              resident_command_id_q[fill_buffer_sel] <= fill_target_command_id_q;
              resident_head_base_q[fill_buffer_sel] <= fill_target_head_base_q;
              resident_wave_index_q[fill_buffer_sel] <= fill_target_wave_index_q;
            end
          end
        end
      end

      if (command_valid && command_ready) begin
        command_active_q <= 1'b1;
        command_buffer_q <= command_buffer_sel;
        active_command_id_q <= command_id;
        active_head_base_q <= command_head_base;
        active_wave_index_q <= command_wave_index;
        command_accept_count_q <= command_accept_count_q + 1'b1;
      end

      if (command_release_valid) begin
        if (!command_active_q || command_release_buffer_sel != command_buffer_q || (|lane_resp_valid_q)) begin
          protocol_error_command_q <= 1'b1;
        end else begin
          command_active_q <= 1'b0;
          fill_target_resident_q[command_release_buffer_sel] <= 1'b0;
          fill_target_count_q[command_release_buffer_sel] <= 0;
          command_release_count_q <= command_release_count_q + 1'b1;
        end
      end

      for (lane = 0; lane < LANES; lane = lane + 1) begin
        if (lane_resp_valid_q[lane] && value_response_ready[lane]) begin
          lane_resp_valid_q[lane] <= 1'b0;
          response_accept_delta_r = response_accept_delta_r + 1;
        end else if (lane_resp_valid_q[lane]) begin
          response_stall_delta_r = response_stall_delta_r + 1;
        end
        if (value_read_req_valid[lane] && !value_read_req_ready[lane])
          request_stall_delta_r = request_stall_delta_r + 1;
      end

      for (bank = 0; bank < BANKS; bank = bank + 1) begin
        if (bank_candidate_count_r[bank] > 1)
          bank_conflict_delta_r = bank_conflict_delta_r + (bank_candidate_count_r[bank] - 1);
        if (selected_lane_r[bank] >= 0 &&
            value_read_req_valid[selected_lane_r[bank]] &&
            value_read_req_ready[selected_lane_r[bank]]) begin
          selected_producer_r = selected_lane_r[bank] / STREAMS;
          relative_addr_r =
              value_read_req_address[(selected_lane_r[bank] * VALUE_REQ_ADDR_W) +: VALUE_REQ_ADDR_W];
          selected_slice_r =
              value_read_req_slice[(selected_lane_r[bank] * VALUE_SLICE_W) +: VALUE_SLICE_W];
          resolved_slot_base_r = resolve_slot_base(selected_producer_r, active_head_base_q);
          resolved_block_count_r = resolve_block_count(selected_producer_r, active_head_base_q);
          selected_block_slot_r = resolved_slot_base_r + (relative_addr_r & 7);
          selected_row_r = (selected_lane_r[bank] % STREAMS) * BLOCK_SLOTS_PER_STREAM + selected_block_slot_r;
          lane_resp_valid_q[selected_lane_r[bank]] <= 1'b1;
          lane_resp_address_q[selected_lane_r[bank]] <= relative_addr_r;
          lane_resp_slice_q[selected_lane_r[bank]] <= selected_slice_r;
          lane_resp_tag_q[selected_lane_r[bank]] <=
              build_resp_tag(selected_lane_r[bank], relative_addr_r, selected_slice_r);
          if ((relative_addr_r >> 3) != 0 || ((relative_addr_r & 7) >= resolved_block_count_r)) begin
            lane_resp_data_q[selected_lane_r[bank]] <= {{ROW_BITS{{1'b0}}}};
            protocol_error_invalid_address_q <= 1'b1;
          end else if (!row_valid_q[command_buffer_q][selected_slice_r][selected_row_r]) begin
            lane_resp_data_q[selected_lane_r[bank]] <= {{ROW_BITS{{1'b0}}}};
            protocol_error_residency_q <= 1'b1;
          end else begin
            lane_resp_data_q[selected_lane_r[bank]] <= bank_mem[selected_slice_r][command_buffer_q][selected_row_r];
          end
          bank_rr_q[bank] <= (selected_lane_r[bank] + 1) % LANES;
          request_accept_delta_r = request_accept_delta_r + 1;
        end
      end

      request_accept_count_q <= request_accept_count_q + request_accept_delta_r;
      request_stall_cycles_q <= request_stall_cycles_q + request_stall_delta_r;
      response_accept_count_q <= response_accept_count_q + response_accept_delta_r;
      response_stall_cycles_q <= response_stall_cycles_q + response_stall_delta_r;
      bank_conflict_count_q <= bank_conflict_count_q + bank_conflict_delta_r;
    end
  end
endmodule
"""


def generate(config: JsonDict, out_dir: Path) -> None:
    params = _validate(json.loads(json.dumps(config)))
    out_dir.mkdir(parents=True, exist_ok=True)
    top_name = str(params["top_name"])
    producers = int(params["producers"])
    (out_dir / "top.v").write_text(_top(top_name=top_name, producers=producers) + "\n", encoding="utf-8")
    (out_dir / "config.json").write_text(json.dumps(config, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest: JsonDict = {
        "version": 1,
        "generator": "npu/rtlgen/gen_attention_score32_exact_cluster_sram_service_gqa8.py",
        "top_name": top_name,
        "semantic_profile": "attention_score32_exact_cluster_sram_service_gqa8_v1",
        "producers": producers,
        "value_memory_lanes": producers * STREAMS,
        "architecture_metadata": dict(ARCHITECTURE_METADATA),
        "service_model": cluster_sram_service_manifest(producers=producers),
        "equivalence_hash": False,
        "rtl_files": ["top.v"],
        "synthesizability_note": (
            "The control and handshake logic is synthesizable SystemVerilog. The 16-bank inferred "
            "512-bit arrays are not SRAM-macro closed; physical implementation must replace them "
            "with technology memory macros and an initialization-safe valid-bit scheme while "
            "preserving this contract."
        ),
    }
    if isinstance(config.get("probe_defaults"), dict):
        manifest["checked_in_probe_defaults"] = config["probe_defaults"]
    (out_dir / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _load(path: Path) -> JsonDict:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise SystemExit(f"config must decode to a JSON object: {path}")
    return payload


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    generate(_load(args.config), args.out)
    return 0


__all__ = ["build_default_config", "generate", "main"]


if __name__ == "__main__":
    raise SystemExit(main())
