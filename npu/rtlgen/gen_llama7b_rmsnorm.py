#!/usr/bin/env python3
"""Generate the Phase-3 Llama-7B BF16 RMSNorm streaming RTL."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from npu.eval.llama7b_rmsnorm_phase2 import check_seed_rom, load_seed_rom


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _validate(config: dict[str, Any]) -> dict[str, int]:
    if not str(config.get("top_name") or "").strip():
        raise SystemExit("config top_name must not be empty")
    body = config.get("llama7b_rmsnorm")
    if not isinstance(body, dict):
        raise SystemExit("config must contain llama7b_rmsnorm object")
    lanes = int(body.get("lanes", 16))
    if lanes <= 0 or lanes > 64 or 4096 % lanes:
        raise SystemExit("llama7b_rmsnorm.lanes must be a positive divisor of 4096 not greater than 64")
    body["lanes"] = lanes
    return {"lanes": lanes}


def _seed_cases() -> str:
    check_seed_rom()
    return "\n".join(
        f"      8'd{address}: seed_rom = 21'h{word:06x};"
        for address, word in enumerate(load_seed_rom())
    )


def _top(*, top_name: str, lanes: int) -> str:
    beats = 4096 // lanes
    beat_width = max(1, math.ceil(math.log2(beats)))
    template = r"""// Auto-generated by npu/rtlgen/gen_llama7b_rmsnorm.py
module @@TOP@@ (
    input  wire                         clk,
    input  wire                         rst_n,
    input  wire                         in_valid,
    output wire                         in_ready,
    input  wire [@@STREAM_W_MINUS1@@:0] in_row,
    input  wire [@@STREAM_W_MINUS1@@:0] in_gamma,
    input  wire                         in_last,
    output wire                         out_valid,
    input  wire                         out_ready,
    output wire [@@STREAM_W_MINUS1@@:0] out_row,
    output wire                         out_last,
    output wire                         out_protocol_error,
    output reg  [31:0]                  accepted_row_count,
    output reg  [31:0]                  completed_row_count
);
  localparam integer HIDDEN_SIZE = 4096;
  localparam integer LANES = @@LANES@@;
  localparam integer BEATS = @@BEATS@@;
  localparam integer BEAT_W = @@BEAT_W@@;
  localparam [3:0] ACCEPT_MAX = 4'd0, ACCUMULATE_REPLAY = 4'd1,
      F0_NORMALIZE = 4'd2, F1_SEED = 4'd3, F2_Y_SQUARE = 4'd4,
      F3_M_Y_SQUARE = 4'd5, F4_UPDATE = 4'd6, EMIT = 4'd7, DRAIN = 4'd8;

  reg [3:0] state;
  reg [BEAT_W-1:0] input_beat;
  reg [BEAT_W-1:0] replay_beat;
  reg [BEAT_W-1:0] issue_beat;
  reg [15:0] row_mem [0:HIDDEN_SIZE-1];
  reg [15:0] gamma_mem [0:HIDDEN_SIZE-1];

  reg row_has_nonzero;
  reg signed [10:0] max_square_exponent;
  reg sticky_protocol_error;
  reg row_protocol_error;
  reg [47:0] accumulator_mantissa;
  reg signed [10:0] accumulator_lsb_exponent;

  reg [25:0] variance_mantissa_q24;
  reg signed [9:0] variance_exponent_even;
  reg [20:0] seed_q20;
  reg [20:0] y_square_q20;
  reg [21:0] correction_q20;
  reg [20:0] rsqrt_mantissa_q20;
  reg signed [8:0] rsqrt_exponent;

  reg s0_valid, s0_last, s0_error;
  reg [(LANES*28)-1:0] s0_product;
  reg [(LANES*10)-1:0] s0_exponent;
  reg [(LANES*16)-1:0] s0_gamma;
  reg [LANES-1:0] s0_sign;
  reg s1_valid, s1_last, s1_error;
  reg [(LANES*36)-1:0] s1_coefficient;
  reg [(LANES*10)-1:0] s1_exponent;
  reg [LANES-1:0] s1_sign;
  reg s2_valid, s2_last, s2_error;
  reg [(LANES*16)-1:0] s2_data;

  wire s2_ready = !s2_valid || out_ready;
  wire s1_ready = !s1_valid || s2_ready;
  wire s0_ready = !s0_valid || s1_ready;
  wire issue_valid = state == EMIT;

  assign in_ready = state == ACCEPT_MAX;
  assign out_valid = s2_valid;
  assign out_row = s2_data;
  assign out_last = s2_last;
  assign out_protocol_error = s2_error;

  integer lane;
  integer bit_index;
  integer variance_lead;
  integer variance_shift;
  integer memory_index;
  reg [15:0] word_value;
  reg [15:0] coefficient_value;
  reg signed [10:0] term_exponent_value;
  reg signed [10:0] candidate_high;
  reg signed [10:0] beat_max;
  reg signed [10:0] combined_max;
  reg beat_has_nonzero;
  reg beat_invalid;
  reg [39:0] beat_sum;
  reg [35:0] aligned_term;
  reg [48:0] accumulator_next;
  reg signed [10:0] mean_lsb_exponent;
  reg signed [10:0] variance_base_exponent;
  reg signed [10:0] variance_leading_exponent;
  reg signed [10:0] variance_even_temp;
  reg [319:0] variance_exact;
  reg [26:0] variance_rounded;
  reg [95:0] arithmetic_value;
  reg [95:0] arithmetic_rounded;
  reg [41:0] y_square_product;
  reg [46:0] m_y_square_product;
  reg [42:0] update_product;
  reg [21:0] half_m_y_square;
  reg [21:0] update_with_bias;
  reg [7:0] gamma_significand;
  reg signed [10:0] gamma_exponent;

  function automatic [7:0] bf16_significand;
    input [15:0] value;
    begin
      if (value[14:7] == 8'd0)
        bf16_significand = {1'b0, value[6:0]};
      else
        bf16_significand = {1'b1, value[6:0]};
    end
  endfunction

  function automatic signed [10:0] bf16_exponent;
    input [15:0] value;
    begin
      if (value[14:7] == 8'd0)
        bf16_exponent = -11'sd133;
      else
        bf16_exponent = $signed({3'd0, value[14:7]}) - 11'sd134;
    end
  endfunction

  function automatic [15:0] square_coefficient;
    input [15:0] value;
    reg [7:0] significand;
    begin
      significand = bf16_significand(value);
      square_coefficient = significand * significand;
    end
  endfunction

  function automatic signed [10:0] square_term_exponent;
    input [15:0] value;
    begin
      square_term_exponent = bf16_exponent(value) <<< 1;
    end
  endfunction

  function automatic [4:0] leading_index_16;
    input [15:0] value;
    integer index;
    begin
      leading_index_16 = 5'd0;
      for (index = 0; index < 16; index = index + 1)
        if (value[index]) leading_index_16 = index[4:0];
    end
  endfunction

  function automatic [5:0] leading_index_36;
    input [35:0] value;
    integer index;
    begin
      leading_index_36 = 6'd0;
      for (index = 0; index < 36; index = index + 1)
        if (value[index]) leading_index_36 = index[5:0];
    end
  endfunction

  function automatic [35:0] align_square_rne;
    input [15:0] coefficient;
    input signed [10:0] term_exponent;
    input signed [10:0] target_exponent;
    integer amount;
    integer index;
    reg [35:0] quotient;
    reg guard_bit;
    reg sticky_bit;
    begin
      amount = target_exponent - term_exponent;
      quotient = 36'd0;
      guard_bit = 1'b0;
      sticky_bit = 1'b0;
      if (coefficient == 0) begin
        quotient = 36'd0;
      end else if (amount <= 0) begin
        quotient = {20'd0, coefficient} << (-amount);
      end else if (amount <= 16) begin
        quotient = {20'd0, coefficient >> amount};
        guard_bit = coefficient[amount-1];
        for (index = 0; index < 15; index = index + 1)
          if (index < amount-1) sticky_bit = sticky_bit | coefficient[index];
        if (guard_bit && (sticky_bit || quotient[0])) quotient = quotient + 1'b1;
      end
      align_square_rne = quotient;
    end
  endfunction

  function automatic [26:0] rne_shift_320_to_27;
    input [319:0] value;
    input integer amount;
    integer index;
    reg [320:0] quotient;
    reg guard_bit;
    reg sticky_bit;
    begin
      quotient = 321'd0;
      guard_bit = 1'b0;
      sticky_bit = 1'b0;
      if (amount <= 0) begin
        quotient = {1'b0, value} << (-amount);
      end else if (amount <= 320) begin
        quotient = {1'b0, value >> amount};
        guard_bit = value[amount-1];
        for (index = 0; index < 319; index = index + 1)
          if (index < amount-1) sticky_bit = sticky_bit | value[index];
        if (guard_bit && (sticky_bit || quotient[0])) quotient = quotient + 1'b1;
      end
      rne_shift_320_to_27 = quotient[26:0];
    end
  endfunction

  function automatic [95:0] rne_shift_96;
    input [95:0] value;
    input integer amount;
    integer index;
    reg [95:0] quotient;
    reg guard_bit;
    reg sticky_bit;
    begin
      quotient = 96'd0;
      guard_bit = 1'b0;
      sticky_bit = 1'b0;
      if (amount <= 0) begin
        quotient = value << (-amount);
      end else if (amount <= 96) begin
        quotient = value >> amount;
        guard_bit = value[amount-1];
        for (index = 0; index < 95; index = index + 1)
          if (index < amount-1) sticky_bit = sticky_bit | value[index];
        if (guard_bit && (sticky_bit || quotient[0])) quotient = quotient + 1'b1;
      end
      rne_shift_96 = quotient;
    end
  endfunction

  function automatic [36:0] rne_shift_36;
    input [35:0] value;
    input integer amount;
    integer index;
    reg [36:0] quotient;
    reg guard_bit;
    reg sticky_bit;
    begin
      quotient = 37'd0;
      guard_bit = 1'b0;
      sticky_bit = 1'b0;
      if (amount <= 0) begin
        quotient = {1'b0, value} << (-amount);
      end else if (amount <= 36) begin
        quotient = {1'b0, value >> amount};
        guard_bit = value[amount-1];
        for (index = 0; index < 35; index = index + 1)
          if (index < amount-1) sticky_bit = sticky_bit | value[index];
        if (guard_bit && (sticky_bit || quotient[0])) quotient = quotient + 1'b1;
      end
      rne_shift_36 = quotient;
    end
  endfunction

  function automatic [15:0] exact_to_bf16;
    input sign_value;
    input [35:0] coefficient;
    input signed [10:0] exponent_value;
    integer leading_index;
    integer leading_exponent;
    integer amount;
    reg [36:0] rounded;
    reg [8:0] significand;
    reg [7:0] exponent_field;
    begin
      if (coefficient == 0) begin
        exact_to_bf16 = {sign_value, 15'd0};
      end else begin
        leading_index = leading_index_36(coefficient);
        leading_exponent = leading_index + exponent_value;
        if (leading_exponent < -126) begin
          amount = -133 - exponent_value;
          rounded = rne_shift_36(coefficient, amount);
          if (rounded < 128)
            exact_to_bf16 = {sign_value, 8'd0, rounded[6:0]};
          else
            exact_to_bf16 = {sign_value, 8'd1, 7'd0};
        end else begin
          rounded = rne_shift_36(coefficient, leading_index - 7);
          significand = rounded[8:0];
          if (significand == 9'd256) begin
            significand = 9'd128;
            leading_exponent = leading_exponent + 1;
          end
          if (leading_exponent > 127)
            exact_to_bf16 = {sign_value, 8'hff, 7'd0};
          else begin
            exponent_field = leading_exponent + 127;
            exact_to_bf16 = {sign_value, exponent_field, significand[6:0]};
          end
        end
      end
    end
  endfunction

  function automatic [20:0] seed_rom;
    input [7:0] address;
    begin
      case (address)
@@SEED_CASES@@
      default: seed_rom = 21'd0;
      endcase
    end
  endfunction

  function automatic [7:0] variance_rom_address;
    input [25:0] mantissa;
    begin
      variance_rom_address = (mantissa >> 18) - 8'd64;
    end
  endfunction

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= ACCEPT_MAX;
      input_beat <= 0;
      replay_beat <= 0;
      issue_beat <= 0;
      row_has_nonzero <= 1'b0;
      max_square_exponent <= 0;
      sticky_protocol_error <= 1'b0;
      row_protocol_error <= 1'b0;
      accumulator_mantissa <= 0;
      accumulator_lsb_exponent <= 0;
      variance_mantissa_q24 <= 0;
      variance_exponent_even <= 0;
      seed_q20 <= 0;
      y_square_q20 <= 0;
      correction_q20 <= 0;
      rsqrt_mantissa_q20 <= 0;
      rsqrt_exponent <= 0;
      s0_valid <= 1'b0;
      s1_valid <= 1'b0;
      s2_valid <= 1'b0;
      s0_last <= 1'b0;
      s1_last <= 1'b0;
      s2_last <= 1'b0;
      s0_error <= 1'b0;
      s1_error <= 1'b0;
      s2_error <= 1'b0;
      s0_product <= 0;
      s0_exponent <= 0;
      s0_gamma <= 0;
      s0_sign <= 0;
      s1_coefficient <= 0;
      s1_exponent <= 0;
      s1_sign <= 0;
      s2_data <= 0;
      accepted_row_count <= 0;
      completed_row_count <= 0;
    end else begin
      if (s2_ready) begin
        s2_valid <= s1_valid;
        if (s1_valid) begin
          s2_last <= s1_last;
          s2_error <= s1_error;
          for (lane = 0; lane < LANES; lane = lane + 1) begin
            if (s1_error)
              s2_data[(lane*16) +: 16] <= 16'h7fc0;
            else
              s2_data[(lane*16) +: 16] <= exact_to_bf16(
                  s1_sign[lane], s1_coefficient[(lane*36) +: 36],
                  $signed(s1_exponent[(lane*10) +: 10]));
          end
        end
      end

      if (s1_ready) begin
        s1_valid <= s0_valid;
        if (s0_valid) begin
          s1_last <= s0_last;
          s1_error <= s0_error;
          for (lane = 0; lane < LANES; lane = lane + 1) begin
            gamma_significand = bf16_significand(s0_gamma[(lane*16) +: 16]);
            gamma_exponent = bf16_exponent(s0_gamma[(lane*16) +: 16]);
            s1_coefficient[(lane*36) +: 36] <=
                s0_product[(lane*28) +: 28] * gamma_significand;
            s1_exponent[(lane*10) +: 10] <=
                $signed(s0_exponent[(lane*10) +: 10]) + gamma_exponent;
            s1_sign[lane] <= s0_sign[lane] ^ s0_gamma[(lane*16)+15];
          end
        end
      end

      if (s0_ready) begin
        s0_valid <= issue_valid;
        if (issue_valid) begin
          s0_last <= issue_beat == BEATS-1;
          s0_error <= row_protocol_error;
          for (lane = 0; lane < LANES; lane = lane + 1) begin
            memory_index = issue_beat * LANES + lane;
            word_value = row_mem[memory_index];
            s0_product[(lane*28) +: 28] <=
                bf16_significand(word_value) * rsqrt_mantissa_q20;
            s0_exponent[(lane*10) +: 10] <=
                bf16_exponent(word_value) + rsqrt_exponent - 11'sd20;
            s0_gamma[(lane*16) +: 16] <= gamma_mem[memory_index];
            s0_sign[lane] <= word_value[15];
          end
          if (issue_beat == BEATS-1) begin
            issue_beat <= 0;
            state <= DRAIN;
          end else begin
            issue_beat <= issue_beat + 1'b1;
          end
        end
      end

      if (s2_valid && out_ready && s2_last) begin
        completed_row_count <= completed_row_count + 1'b1;
        input_beat <= 0;
        row_has_nonzero <= 1'b0;
        max_square_exponent <= 0;
        sticky_protocol_error <= 1'b0;
        row_protocol_error <= 1'b0;
        accumulator_mantissa <= 0;
        accumulator_lsb_exponent <= 0;
        state <= ACCEPT_MAX;
      end

      if (state == ACCEPT_MAX && in_valid && in_ready) begin
        beat_has_nonzero = 1'b0;
        beat_invalid = 1'b0;
        beat_max = -11'sd1024;
        for (lane = 0; lane < LANES; lane = lane + 1) begin
          memory_index = input_beat * LANES + lane;
          word_value = in_row[(lane*16) +: 16];
          row_mem[memory_index] <= word_value;
          gamma_mem[memory_index] <= in_gamma[(lane*16) +: 16];
          if (word_value[14:7] == 8'hff || in_gamma[(lane*16)+14 -: 8] == 8'hff) begin
            beat_invalid = 1'b1;
          end else begin
            coefficient_value = square_coefficient(word_value);
            if (coefficient_value != 0) begin
              candidate_high = square_term_exponent(word_value) + leading_index_16(coefficient_value);
              if (!beat_has_nonzero || candidate_high > beat_max) beat_max = candidate_high;
              beat_has_nonzero = 1'b1;
            end
          end
        end
        if (in_last != (input_beat == BEATS-1)) beat_invalid = 1'b1;
        sticky_protocol_error <= sticky_protocol_error | beat_invalid;
        if (beat_has_nonzero && (!row_has_nonzero || beat_max > max_square_exponent))
          max_square_exponent <= beat_max;
        row_has_nonzero <= row_has_nonzero | beat_has_nonzero;

        if (input_beat == BEATS-1) begin
          if (row_has_nonzero && (!beat_has_nonzero || max_square_exponent >= beat_max))
            combined_max = max_square_exponent;
          else if (beat_has_nonzero)
            combined_max = beat_max;
          else
            combined_max = 0;
          max_square_exponent <= combined_max;
          accumulator_lsb_exponent <= (row_has_nonzero || beat_has_nonzero) ? combined_max - 11'sd34 : 0;
          row_protocol_error <= sticky_protocol_error | beat_invalid;
          accepted_row_count <= accepted_row_count + 1'b1;
          input_beat <= 0;
          replay_beat <= 0;
          accumulator_mantissa <= 0;
          state <= ACCUMULATE_REPLAY;
        end else begin
          input_beat <= input_beat + 1'b1;
        end
      end

      if (state == ACCUMULATE_REPLAY) begin
        beat_sum = 40'd0;
        for (lane = 0; lane < LANES; lane = lane + 1) begin
          memory_index = replay_beat * LANES + lane;
          word_value = row_mem[memory_index];
          if (word_value[14:7] != 8'hff) begin
            coefficient_value = square_coefficient(word_value);
            term_exponent_value = square_term_exponent(word_value);
            aligned_term = align_square_rne(
                coefficient_value, term_exponent_value, accumulator_lsb_exponent);
            beat_sum = beat_sum + aligned_term;
          end
        end
        accumulator_next = {1'b0, accumulator_mantissa} + beat_sum;
        accumulator_mantissa <= accumulator_next[47:0];
        if (replay_beat == BEATS-1) begin
          replay_beat <= 0;
          state <= F0_NORMALIZE;
        end else begin
          replay_beat <= replay_beat + 1'b1;
        end
`ifndef SYNTHESIS
        if (accumulator_next[48]) $fatal(1, "RMSNorm 48-bit accumulator overflow");
`endif
      end

      if (state == F0_NORMALIZE) begin
        mean_lsb_exponent = accumulator_lsb_exponent - 11'sd12;
        variance_exact = 320'd0;
        if (mean_lsb_exponent <= -11'sd40) begin
          variance_base_exponent = mean_lsb_exponent;
          variance_exact = {{272{1'b0}}, accumulator_mantissa};
          variance_exact = variance_exact +
              ({{299{1'b0}}, 21'd1099512} << (-40 - mean_lsb_exponent));
        end else begin
          variance_base_exponent = -11'sd40;
          variance_exact = ({{272{1'b0}}, accumulator_mantissa} << (mean_lsb_exponent + 40)) +
              {{299{1'b0}}, 21'd1099512};
        end
        variance_lead = 0;
        for (bit_index = 0; bit_index < 320; bit_index = bit_index + 1)
          if (variance_exact[bit_index]) variance_lead = bit_index;
        variance_leading_exponent = variance_base_exponent + variance_lead;
        if (variance_leading_exponent[0])
          variance_even_temp = variance_leading_exponent - 1'b1;
        else
          variance_even_temp = variance_leading_exponent;
        variance_shift = variance_even_temp - 24 - variance_base_exponent;
        variance_rounded = rne_shift_320_to_27(variance_exact, variance_shift);
        if (variance_rounded == 27'h4000000) begin
          variance_mantissa_q24 <= 26'h1000000;
          variance_exponent_even <= variance_even_temp + 2;
        end else begin
          variance_mantissa_q24 <= variance_rounded[25:0];
          variance_exponent_even <= variance_even_temp[9:0];
        end
        state <= F1_SEED;
      end

      if (state == F1_SEED) begin
        seed_q20 <= seed_rom(variance_rom_address(variance_mantissa_q24));
        state <= F2_Y_SQUARE;
      end

      if (state == F2_Y_SQUARE) begin
        y_square_product = seed_q20 * seed_q20;
        arithmetic_value = {{54{1'b0}}, y_square_product};
        arithmetic_rounded = rne_shift_96(arithmetic_value, 20);
        y_square_q20 <= arithmetic_rounded[20:0];
        state <= F3_M_Y_SQUARE;
      end

      if (state == F3_M_Y_SQUARE) begin
        m_y_square_product = variance_mantissa_q24 * y_square_q20;
        arithmetic_value = {{49{1'b0}}, m_y_square_product};
        arithmetic_rounded = rne_shift_96(arithmetic_value, 25);
        half_m_y_square = arithmetic_rounded[21:0];
        correction_q20 <= 22'd1572864 - half_m_y_square;
        state <= F4_UPDATE;
      end

      if (state == F4_UPDATE) begin
        update_product = seed_q20 * correction_q20;
        arithmetic_value = {{53{1'b0}}, update_product};
        arithmetic_rounded = rne_shift_96(arithmetic_value, 20);
        update_with_bias = arithmetic_rounded[21:0] + 22'd4;
        if (update_with_bias > 22'h1fffff)
          rsqrt_mantissa_q20 <= 21'h1fffff;
        else
          rsqrt_mantissa_q20 <= update_with_bias[20:0];
        rsqrt_exponent <= -($signed(variance_exponent_even) >>> 1);
        issue_beat <= 0;
        state <= EMIT;
      end
    end
  end
endmodule
"""
    replacements = {
        "@@TOP@@": top_name,
        "@@LANES@@": str(lanes),
        "@@BEATS@@": str(beats),
        "@@BEAT_W@@": str(beat_width),
        "@@STREAM_W_MINUS1@@": str(lanes * 16 - 1),
        "@@SEED_CASES@@": _seed_cases(),
    }
    for needle, replacement in replacements.items():
        template = template.replace(needle, replacement)
    return template


def generate(config: dict[str, Any], out_dir: Path) -> None:
    params = _validate(config)
    top_name = str(config["top_name"])
    lanes = params["lanes"]
    beats = 4096 // lanes
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "top.v").write_text(_top(top_name=top_name, lanes=lanes), encoding="utf-8")
    (out_dir / "config.json").write_text(json.dumps(config, indent=2, sort_keys=True) + "\n", encoding="utf-8")
